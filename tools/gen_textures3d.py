#!/usr/bin/env python3
"""gen_textures3d.py - deterministic hand-painted style textures for the 3D
diorama (Fase 2). Pure procedural (seeded), so nothing enters the repo that
is not generated by this script: license-clean and reproducible.

Outputs (256x256 PNG, sRGB):
  assets/textures3d/tex_wood_board.png    warm planks (ring / column blocks)
  assets/textures3d/tex_wood_board_n.png  matching tangent normal map
  assets/textures3d/tex_stone_floor.png   night-blue slabs (floor / walls)
  assets/textures3d/tex_stone_floor_n.png matching tangent normal map
  assets/textures3d/tex_rune.png          emission glyphs (goals / markers)

Palette gate (tools/audit_palette.py) constraints respected by design:
no neon cyan / neon green; all hues are wood-orange, night blue or cream.
"""
import numpy as np
from PIL import Image, ImageFilter
from pathlib import Path

SEED = 1337
SIZE = 256
OUT = Path(__file__).resolve().parent.parent / "assets" / "textures3d"


def sobel_normal(height: np.ndarray, strength: float = 2.5) -> Image.Image:
    """Height field (float 0..1) -> tangent-space normal map RGB."""
    h = height.astype(np.float64)
    gy, gx = np.gradient(h)
    dx = gx * strength
    dy = gy * strength
    n = np.dstack([-dx, -dy, np.ones_like(h)])
    n /= np.linalg.norm(n, axis=2, keepdims=True)
    rgb = (n * 0.5 + 0.5) * 255.0
    return Image.fromarray(rgb.astype(np.uint8), "RGB")


def smooth_noise(rng, size, cells, smooth=1):
    """Tileable value noise: random grid upsampled with bilinear filter."""
    g = rng.random((cells, cells))
    img = Image.fromarray((g * 255).astype(np.uint8), "L").resize(
        (size, size), Image.BILINEAR)
    for _ in range(smooth):
        img = img.filter(ImageFilter.SMOOTH_MORE)
    return np.asarray(img, dtype=np.float64) / 255.0


# --------------------------------------------------------------- wood -----

def gen_wood(rng):
    yy, xx = np.mgrid[0:SIZE, 0:SIZE].astype(np.float64)
    planks = 4
    ph = SIZE / planks
    # plank seams (deep grooves) + per-plank tone
    plank_id = (yy // ph).astype(int)
    seam = np.zeros((SIZE, SIZE))
    for p in range(planks):
        y0 = int(p * ph)
        seam[y0:y0 + 3, :] = 1.0            # 3px dark seam under each plank
    plank_tone = rng.uniform(-0.06, 0.06, planks)[plank_id]
    # grain: stretched noise streaks along x + fine sine ripples
    grain_n = smooth_noise(rng, SIZE, 32, smooth=2)
    streak = smooth_noise(rng, SIZE, 4, smooth=1)
    grain = np.sin(xx * 0.55 + streak * 9.0) * 0.5 + 0.5
    grain = grain * 0.65 + grain_n * 0.35
    # knots: a few elliptical dark spots
    knots = np.zeros((SIZE, SIZE))
    for _ in range(5):
        kx, ky = rng.uniform(0, SIZE, 2)
        kr = rng.uniform(3.0, 7.0)
        d = ((xx - kx) ** 2) / (kr * kr) + ((yy - ky) ** 2) / ((kr * 2.2) ** 2)
        knots = np.maximum(knots, np.clip(1.0 - d, 0.0, 1.0))
    base = np.array([0.463, 0.322, 0.200])                    # warm wood
    shade = 0.72 + grain * 0.30 + plank_tone - knots * 0.35
    shade -= seam * 0.45
    img = np.clip(shade[..., None] * base[None, None, :], 0.0, 1.0)
    # nail dots near plank ends
    for p in range(planks):
        for nx in (18, SIZE - 18):
            ny = int(p * ph + ph * 0.5)
            yy2, xx2 = np.mgrid[0:SIZE, 0:SIZE]
            d = (xx2 - nx) ** 2 + (yy2 - ny) ** 2
            img[d < 4.0] *= 0.45
    # height: seams deep, grain mid, knots low
    height = 0.75 + grain * 0.18 - seam * 0.55 - knots * 0.30
    return Image.fromarray((img * 255).astype(np.uint8), "RGB"), height


# -------------------------------------------------------------- stone -----

def gen_stone(rng):
    yy, xx = np.mgrid[0:SIZE, 0:SIZE].astype(np.float64)
    cols, rows = 4, 4
    cw, rh = SIZE / cols, SIZE / rows
    # irregular slab borders: jittered vertical + horizontal lines
    edge = np.zeros((SIZE, SIZE))
    slab_id = np.zeros((SIZE, SIZE), dtype=int)
    for c in range(cols + 1):
        x = int(c * cw + rng.uniform(-6, 6))
        if 0 < x < SIZE:
            edge[:, max(0, x - 1):x + 2] = 1.0
            slab_id[:, x:] += 1
    for r in range(rows + 1):
        y = int(r * rh + rng.uniform(-6, 6))
        if 0 < y < SIZE:
            edge[max(0, y - 1):y + 2, :] = 1.0
            slab_id[y:, :] += cols
    n_slab = int(slab_id.max()) + 1
    tone = rng.uniform(-0.10, 0.10, n_slab)
    slab_tone = tone[np.clip(slab_id, 0, n_slab - 1)]
    # cracks: short random walks from slab corners
    cracks = np.zeros((SIZE, SIZE))
    for _ in range(14):
        cx, cy = rng.uniform(0, SIZE, 2)
        ang = rng.uniform(0, 2 * np.pi)
        for _step in range(rng.integers(8, 40)):
            cx += np.cos(ang) * 1.6
            cy += np.sin(ang) * 1.6
            ang += rng.uniform(-0.5, 0.5)
            if 0 <= int(cx) < SIZE and 0 <= int(cy) < SIZE:
                cracks[int(cy), int(cx)] = 1.0
    cracks = np.asarray(
        Image.fromarray((cracks * 255).astype(np.uint8)).filter(
            ImageFilter.MaxFilter(3)), dtype=np.float64) / 255.0
    speck = smooth_noise(rng, SIZE, 64, smooth=1)
    base = np.array([0.102, 0.086, 0.200])                    # night violet #1a1633
    shade = 0.80 + slab_tone + speck * 0.18
    shade -= edge * 0.62
    shade -= cracks * 0.30
    img = np.clip(shade[..., None] * base[None, None, :], 0.0, 1.0)
    height = 0.72 + speck * 0.15 - edge * 0.65 - cracks * 0.35
    return Image.fromarray((img * 255).astype(np.uint8), "RGB"), height


# --------------------------------------------------------------- runes -----

def gen_rune(rng):
    """Emission glyphs: dashed concentric ring + radial ticks + 4 rune cards,
    moon-cream strokes with one toxic-green and one pumpkin-orange arc."""
    img = np.zeros((SIZE, SIZE, 3))
    yy, xx = np.mgrid[0:SIZE, 0:SIZE].astype(np.float64)
    cx = cy = SIZE / 2.0
    dx, dy = xx - cx, yy - cy
    r = np.sqrt(dx * dx + dy * dy) / (SIZE / 2.0)             # 0..1 at edge
    ang = (np.arctan2(dy, dx) + np.pi) / (2 * np.pi)          # 0..1

    cream = np.array([0.953, 0.914, 0.784])
    green = np.array([0.498, 0.659, 0.369])                   # spectral
    orange = np.array([0.910, 0.525, 0.180])

    mask = np.zeros((SIZE, SIZE))
    color = np.zeros((SIZE, SIZE, 3))
    # two dashed rings
    for rr, dash_n, lw in ((0.30, 24, 0.012), (0.52, 36, 0.010)):
        band = np.abs(r - rr) < lw
        phase = (ang * dash_n) % 1.0
        dash = (phase < 0.55) & band
        mask = np.maximum(mask, dash)
        color[dash] = cream
    # radial ticks every 15 deg
    tick_ang = ((ang * 24) % 1.0) < 0.10
    ticks = tick_ang & (r > 0.30) & (r < 0.52)
    mask = np.maximum(mask, ticks)
    color[ticks] = cream * 0.7
    # green arc + orange arc
    green_arc = (np.abs(r - 0.41) < 0.012) & (ang > 0.62) & (ang < 0.80)
    orange_arc = (np.abs(r - 0.41) < 0.012) & (ang > 0.12) & (ang < 0.30)
    mask = np.maximum(mask, green_arc)
    mask = np.maximum(mask, orange_arc)
    color[green_arc] = green
    color[orange_arc] = orange
    # 4 rune cards: inscribed square strokes at the diagonals
    for i in range(4):
        a0 = i * 0.25 + 0.02
        a1 = a0 + 0.21
        sel = (ang > a0) & (ang < a1) & (r > 0.60) & (r < 0.86)
        # carve glyph: vertical stem + two branches, deterministic per card
        stem = sel & (np.abs(dx) < 0.030 * SIZE) & (r > 0.64)
        br1 = sel & (np.abs(dy) < 0.030 * SIZE) & (ang % 0.25 > 0.08) \
            & (ang % 0.25 < 0.14) & (r > 0.64)
        card = stem | br1
        mask = np.maximum(mask, card)
        tone = cream if i % 2 == 0 else green * 0.85 + cream * 0.15
        color[card] = tone
    img = color * np.clip(mask, 0, 1)[..., None]
    # slight bloom-friendly softness
    out = Image.fromarray((np.clip(img, 0, 1) * 255).astype(np.uint8), "RGB")
    out = out.filter(ImageFilter.GaussianBlur(0.6))
    return out


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(SEED)
    wood, wood_h = gen_wood(rng)
    wood.save(OUT / "tex_wood_board.png")
    sobel_normal(wood_h).save(OUT / "tex_wood_board_n.png")
    stone, stone_h = gen_stone(rng)
    stone.save(OUT / "tex_stone_floor.png")
    sobel_normal(stone_h).save(OUT / "tex_stone_floor_n.png")
    rune = gen_rune(rng)
    rune.save(OUT / "tex_rune.png")
    print("textures written to", OUT)


if __name__ == "__main__":
    main()
